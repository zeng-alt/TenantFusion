-- H2 / PostgreSQL fresh installation
CREATE TABLE IF NOT EXISTS sys_config_app (
    app_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_code VARCHAR(64) NOT NULL UNIQUE,
    app_name VARCHAR(128),
    description VARCHAR(512),
    status INTEGER DEFAULT 1,
    tenant_id VARCHAR(255),
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_modified_by VARCHAR(255),
    last_modified_date TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sys_config_info (
    config_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id BIGINT NOT NULL REFERENCES sys_config_app(app_id),
    data_id VARCHAR(255) NOT NULL,
    group_name VARCHAR(128) NOT NULL DEFAULT 'DEFAULT_GROUP',
    content TEXT,
    format VARCHAR(32) DEFAULT 'properties',
    description VARCHAR(512),
    version INTEGER DEFAULT 0,
    status VARCHAR(32) DEFAULT 'draft',
    tenant_id VARCHAR(255),
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_modified_by VARCHAR(255),
    last_modified_date TIMESTAMP,
    UNIQUE (app_id, data_id, group_name)
);

CREATE TABLE IF NOT EXISTS sys_config_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id BIGINT NOT NULL,
    content TEXT,
    version INTEGER,
    operation VARCHAR(32),
    operator VARCHAR(64),
    created_date TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sys_config_release (
    release_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id BIGINT NOT NULL REFERENCES sys_config_app(app_id),
    config_ids VARCHAR(2048),
    release_version VARCHAR(64),
    release_note VARCHAR(1024),
    status VARCHAR(32) DEFAULT 'published',
    snapshot TEXT,
    tenant_id VARCHAR(255),
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_modified_by VARCHAR(255),
    last_modified_date TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sys_config_client_instance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_code VARCHAR(64) NOT NULL,
    ip VARCHAR(64),
    instance_id VARCHAR(128),
    client_version VARCHAR(32),
    last_heartbeat TIMESTAMP,
    status VARCHAR(32) DEFAULT 'ONLINE',
    tenant_id VARCHAR(255),
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_modified_by VARCHAR(255),
    last_modified_date TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_config_release_app ON sys_config_release (app_id, release_id);
CREATE INDEX IF NOT EXISTS idx_config_history_config ON sys_config_history (config_id, version);
